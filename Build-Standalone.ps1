param(
    [Parameter(Mandatory=$true)][string]$PayloadZip,
    [Parameter(Mandatory=$true)][string]$OutputExe
)
$ErrorActionPreference='Stop'
$payload=[IO.Path]::GetFullPath($PayloadZip)
$output=[IO.Path]::GetFullPath($OutputExe)
if(!(Test-Path -LiteralPath $payload -PathType Leaf)){throw 'Supply the portable ZIP generated by package_toolchain.py'}
if(Test-Path -LiteralPath $output){throw 'The standalone output already exists; choose a new output path.'}
$hash=(Get-FileHash -LiteralPath $payload -Algorithm SHA256).Hash.ToLowerInvariant()
$compiler=Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if(!(Test-Path -LiteralPath $compiler)){throw '.NET Framework C# compiler not found'}
$build=Join-Path $PSScriptRoot ('tools\bootstrap-build\'+[Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $build,([IO.Path]::GetDirectoryName($output)) -Force | Out-Null
$config=Join-Path $build 'BootstrapConfig.cs'
$configText='internal static class BootstrapConfig { internal const string PayloadSha256 = "'+$hash+'"; }'
[IO.File]::WriteAllText($config,$configText,[Text.Encoding]::ASCII)
$source=Join-Path $PSScriptRoot 'src\ToolBootstrap.cs'
$manifest=Join-Path $PSScriptRoot 'src\ToolBootstrap.manifest'
& $compiler /nologo /optimize+ /target:winexe /platform:x64 "/out:$output" "/win32manifest:$manifest" "/resource:$payload,VdOfflinePayload.zip" /reference:System.dll /reference:System.Core.dll /reference:System.Drawing.dll /reference:System.Windows.Forms.dll /reference:System.Web.Extensions.dll /reference:System.IO.Compression.dll /reference:System.IO.Compression.FileSystem.dll $source $config
if($LASTEXITCODE -ne 0){throw 'Standalone bootstrapper compilation failed'}
$receipt=[ordered]@{schema_version=1;payload_sha256=$hash;payload_size=(Get-Item -LiteralPath $payload).Length;executable_sha256=(Get-FileHash -LiteralPath $output -Algorithm SHA256).Hash.ToLowerInvariant();executable_size=(Get-Item -LiteralPath $output).Length;target_framework='net48';architecture='x64';runtime_install_required=$false;gui_launched=$false}
$receipt | ConvertTo-Json | Set-Content -LiteralPath ($output+'.build.json') -Encoding UTF8
$receipt | ConvertTo-Json
